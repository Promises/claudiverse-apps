package dev.claudiverse.core

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.jsonObject
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/** A slash command run at the seat reads as what was typed and its output, never raw tags. */
class LocalCommandTest {

    private fun user(uuid: String, content: String, meta: Boolean = false): JsonObject = Json.parseToJsonElement(
        """{"type":"user","uuid":"$uuid"${if (meta) ""","isMeta":true""" else ""},"message":{"role":"user","content":${Json.encodeToString(kotlinx.serialization.json.JsonPrimitive.serializer(), kotlinx.serialization.json.JsonPrimitive(content))}}}""",
    ).jsonObject

    private fun userBlocks(uuid: String, text: String): JsonObject = Json.parseToJsonElement(
        """{"type":"user","uuid":"$uuid","message":{"role":"user","content":[{"type":"text","text":${kotlinx.serialization.json.JsonPrimitive(text)}}]}}""",
    ).jsonObject

    private fun build(vararg m: JsonObject) = TranscriptBuilder.build(m.toList(), emptySet())

    @Test
    fun exitReadsAsTypedWithItsOutputAndNoCaveat() {
        val items = build(
            user("c", "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>", meta = true),
            user("n", "<command-name>/exit</command-name>\n<command-message>exit</command-message>\n<command-args></command-args>"),
            user("o", "<local-command-stdout>Bye!</local-command-stdout>"),
        )
        assertEquals(2, items.size, "$items")
        assertEquals("/exit", (items[0] as TranscriptItem.UserText).text)
        val out = items[1] as TranscriptItem.Event
        assertEquals("Command output" to "Bye!", out.label to out.text)
        assertTrue(items.none { it.toString().contains("<command-") || it.toString().contains("<local-command") })
    }

    @Test
    fun argsBlocksStderrAndEmptyOutput() {
        val items = build(
            userBlocks("n", "<command-message>model</command-message>\n<command-name>/model</command-name>\n<command-args>claude-opus-5-5</command-args>"),
            user("e", "<local-command-stderr>no such model</local-command-stderr>"),
            user("x", "<local-command-stdout></local-command-stdout>"),
        )
        assertEquals("/model claude-opus-5-5", (items[0] as TranscriptItem.UserText).text)
        assertEquals("Command error", (items[1] as TranscriptItem.Event).label)
        assertEquals(2, items.size, "empty output shows nothing")
    }

    @Test
    fun aMessageQuotingTheTagsIsStillTheOperators() {
        val text = "why does it show <command-name>/exit</command-name> raw?"
        assertEquals(text, (build(user("q", text)).single() as TranscriptItem.UserText).text)
    }
}
